        // Latch before the first write, including partially failed restores.
        Plugin.Instance!.SessionModified = true;
        var c = b.kartController; var p = c.kartPhysics; var r = c.outsideMapValidator;
        float elapsed = Time.time - CapturedTime;
        var race = c.parentPlayer.playerRaceLogic;
        race.fPlayerCurrentRoadDistance = RoadDistance; c.parentPlayer.fDistanceOnTrack = PlayerDistance;
        race.closestPosPointOnTrack = Closest; race.closestPosPointOnTrack_UnlockedRoadsOnly = ClosestUnlocked;
        r.lastCorrectCloestPointWhileGrounded = LastGroundedRespawnPoint;
        race.fLastCheckpointResetTime = Rebase(LastCheckpointReset, elapsed); race.fLastDistanceToFinish = LastFinishDistance;
        race.dLastFinishLineSampleNetworkTime = Photon.Pun.PhotonNetwork.Time - LastFinishSampleAge;
        race.lastDistanceToForwardCheckpoints.Clear();
        foreach (var pair in CheckpointDistances) race.lastDistanceToForwardCheckpoints.Add(pair.Key, pair.Value);
        race.movedThroughCheckpointCount.Clear();
        foreach (var pair in CheckpointCrossings) race.movedThroughCheckpointCount.Add(pair.Key, pair.Value);
        var smooth = b.continousBoostMaxSpeedClearSpeed;
        smooth.vLastCurrent = BoostSmoothCurrent; smooth.vLastTarget = BoostSmoothTarget;
        smooth.vCurrentVel = BoostSmoothVelocity; smooth.vCurrentWorld = BoostSmoothWorld;
        smooth.qCurrentWorld = BoostSmoothRotation; smooth.bCurrWorldInitialized = BoostSmoothInitialized;
